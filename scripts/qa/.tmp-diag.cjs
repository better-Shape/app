const { chromium } = require("playwright");
const { default: sparticuz } = require("@sparticuz/chromium");
const { applySandboxLibs } = require("/home/user/app/scripts/qa/sandbox-libs.cjs");
applySandboxLibs();
const BASE = "http://127.0.0.1:48922";
(async () => {
  const browser = await chromium.launch({ executablePath: await sparticuz.executablePath(), args: ["--no-sandbox", "--disable-dev-shm-usage"] });
  const page = await browser.newPage({ viewport: { width: 1280, height: 900 } });
  await page.goto(`${BASE}/settings?category=git`, { waitUntil: "domcontentloaded", timeout: 120000 });
  await page.waitForTimeout(2000);
  const sw = page.locator("div").filter({ hasText: /^Inline Git Blame/ }).locator('[role="switch"]').first();
  if ((await sw.getAttribute("data-state")) !== "checked") await sw.click();
  await page.goto(`${BASE}/?seed=project`, { waitUntil: "domcontentloaded", timeout: 120000 });
  await page.waitForTimeout(3000);
  await page.getByRole("button", { name: "New tab" }).first().click();
  await page.waitForTimeout(400);
  await page.getByRole("menuitem", { name: "Files" }).first().click();
  await page.waitForTimeout(1200);
  await page.locator('[data-explorer-root="true"]').getByText("README.md", { exact: true }).first().click();
  await page.waitForTimeout(1500);
  const vs = page.getByRole("button", { name: /view source/i }).first();
  if (await vs.count()) await vs.click();
  await page.waitForTimeout(2500);
  const info = await page.evaluate(() => {
    const node = document.querySelector(".cm-inline-blame");
    const ed = document.querySelector(".cm-editor");
    if (!node || !ed) return { node: Boolean(node), ed: Boolean(ed) };
    const b = node.getBoundingClientRect();
    const v = ed.getBoundingClientRect();
    return { node: b.toJSON(), view: v.toJSON(), cls: node.className, tag: node.tagName, text: node.textContent };
  });
  console.log(JSON.stringify(info));
  await browser.close();
})();
